"""Embed the canonical refusal policy for Node and Frida without runtime I/O."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
POLICY = ROOT / "sora_bilingual/localization/effect_refusal_policy.json"
RUNTIME = ROOT / "sora_bilingual/game/scripts/runtime_text.js"
BEGIN = "// BEGIN EFFECT REFUSAL POLICY"
END = "// END EFFECT REFUSAL POLICY"


def generate(*, policy_path=POLICY, runtime_path=RUNTIME, check=False):
    policy = json.loads(policy_path.read_text("utf-8"))
    if (
        not isinstance(policy, dict)
        or not policy
        or any(
            not re.fullmatch(r"[a-z_]+", reason) or value not in {"hard", "unproved"}
            for reason, value in policy.items()
        )
    ):
        raise ValueError("invalid effect refusal policy")
    source = runtime_path.read_text("utf-8")
    embed = (
        BEGIN
        + "\n// Generated by tools/generate_effect_refusal_policy.py; edit effect_refusal_policy.json.\n"
        + "RuntimeText.effectRefusalPolicy=Object.freeze("
        + json.dumps(policy, separators=(",", ":"))
        + ");\n"
        + END
    )
    updated, count = re.subn(
        re.escape(BEGIN) + r"\n.*?" + re.escape(END), embed, source, flags=re.S
    )
    if count != 1:
        raise ValueError("effect refusal policy marker missing or duplicated")
    if check:
        return source == updated
    if source != updated:
        runtime_path.write_text(updated, "utf-8")
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="reject stale generated policy")
    args = parser.parse_args()
    if not generate(check=args.check):
        parser.exit(
            1, "embedded refusal policy is stale; run tools.generate_effect_refusal_policy\n"
        )


if __name__ == "__main__":
    main()
